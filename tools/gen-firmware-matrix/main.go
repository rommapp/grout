package main

import (
	"bytes"
	"flag"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/rommapp/grout/core/firmware"
)

const defaultOut = "docs/firmware-matrix.md"

func main() {
	check := flag.Bool("check", false, "fail when the output file is stale")
	out := flag.String("out", defaultOut, "output file")
	flag.Parse()

	defs, err := firmware.LoadAll()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	content := render(defs)

	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(existing, []byte(content)) {
			fmt.Fprintf(os.Stderr, "%s is stale; run: go run ./tools/gen-firmware-matrix\n", *out)
			os.Exit(1)
		}
		return
	}

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type cellFn func(d *firmware.Definition) string

type row struct {
	label string
	cell  cellFn
}

type section struct {
	title string
	rows  []row
}

func render(defs []*firmware.Definition) string {
	sorted := append([]*firmware.Definition(nil), defs...)
	sort.SliceStable(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })

	var b strings.Builder
	b.WriteString("# Firmware matrix\n\n")
	b.WriteString("Generated by tools/gen-firmware-matrix from core/firmware/*/firmware.toml. Do not edit.\n")
	if len(sorted) == 0 {
		b.WriteString("\nNo firmware definitions yet.\n")
		return b.String()
	}

	b.WriteString("\n## Upstream\n\n")
	writeTable(&b, []string{"Firmware", "Repository", "Ref", "Maintained"}, upstreamRows(sorted))

	for _, s := range sections() {
		b.WriteString("\n## " + s.title + "\n\n")
		header := []string{""}
		for _, d := range sorted {
			header = append(header, cellText(d.ID))
		}
		var rows [][]string
		for _, r := range s.rows {
			line := []string{r.label}
			for _, d := range sorted {
				line = append(line, r.cell(d))
			}
			rows = append(rows, line)
		}
		writeTable(&b, header, rows)
	}

	b.WriteString("\n## Platforms\n\n")
	header := []string{"Platform"}
	for _, d := range sorted {
		header = append(header, cellText(d.ID))
	}
	writeTable(&b, header, platformRows(sorted))
	return b.String()
}

func writeTable(b *strings.Builder, header []string, rows [][]string) {
	writeLine(b, header)
	sep := make([]string, len(header))
	for i := range sep {
		sep[i] = "---"
	}
	writeLine(b, sep)
	for _, r := range rows {
		writeLine(b, r)
	}
}

func writeLine(b *strings.Builder, cells []string) {
	b.WriteString("|")
	for _, c := range cells {
		b.WriteString(" " + c + " |")
	}
	b.WriteString("\n")
}

func cellText(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

func upstreamRows(defs []*firmware.Definition) [][]string {
	var rows [][]string
	for _, d := range defs {
		repo, ref := "", ""
		if d.Upstream.Repo != "" {
			repo = fmt.Sprintf("[%s](https://%s)", cellText(d.Upstream.Repo), d.Upstream.Repo)
			ref = cellText(d.Upstream.Ref)
		}
		rows = append(rows, []string{cellText(d.Name), repo, ref, cellText(d.Maintained)})
	}
	return rows
}

func sections() []section {
	return []section{
		{"Paths", []row{
			{"card", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Paths.Card })},
			{"roms", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Paths.Roms })},
			{"bios", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Paths.Bios })},
			{"saves", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Paths.Saves })},
			{"version source", versionCell},
		}},
		{"Saves", []row{
			{"layout", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Saves.Layout })},
			{"naming", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Saves.Naming })},
			{"hooks", savesHooksCell},
		}},
		{"ROM folders", []row{
			{"style", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.RomFolders.Style })},
			{"multi layout", func(d *firmware.Definition) string {
				if d.RomFolders.MultiLayout == "" {
					return ""
				}
				return "hook: " + cellText(d.RomFolders.MultiLayout)
			}},
		}},
		{"BIOS", []row{
			{"default", factCell(func(d *firmware.Definition) *firmware.Fact { return &d.Bios.Default })},
		}},
		{"Art", []row{
			{"naming", func(d *firmware.Definition) string { return cellText(d.Art.Naming) }},
			{"cover", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Cover })},
			{"preview", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Preview })},
			{"splash", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Splash })},
			{"video", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Video })},
			{"manual", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Manual })},
			{"bezel", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Bezel })},
			{"marquee", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Marquee })},
			{"thumbnail", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Thumbnail })},
			{"boxback", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Boxback })},
			{"fanart", factCell(func(d *firmware.Definition) *firmware.Fact { return d.Art.Fanart })},
		}},
		{"Gamelist", []row{
			{"format", func(d *firmware.Definition) string { return cellText(d.Gamelist.Format) }},
			{"launcher entry", launcherCell},
		}},
		{"RetroArch", []row{
			{"config", factCell(func(d *firmware.Definition) *firmware.Fact {
				if d.RetroArch == nil {
					return nil
				}
				return d.RetroArch.Config
			})},
			{"overrides", factCell(func(d *firmware.Definition) *firmware.Fact {
				if d.RetroArch == nil {
					return nil
				}
				return d.RetroArch.Overrides
			})},
		}},
		{"Devices", []row{
			{"default", func(d *firmware.Definition) string { return cellText(d.Devices.Default) }},
			{"rules", rulesCell},
			{"inputs", inputsCell},
			{"quirks", quirksCell},
		}},
		{"Packaging", []row{
			{"asset", func(d *firmware.Definition) string { return cellText(d.Packaging.Asset) }},
			{"launch script", func(d *firmware.Definition) string { return cellText(d.Packaging.LaunchScript) }},
			{"install depth", func(d *firmware.Definition) string { return strconv.Itoa(d.Packaging.InstallDepth) }},
			{"files", func(d *firmware.Definition) string { return cellText(strings.Join(d.Packaging.Files, ", ")) }},
		}},
	}
}

func factCell(get func(d *firmware.Definition) *firmware.Fact) cellFn {
	return func(d *firmware.Definition) string {
		f := get(d)
		if f == nil {
			return ""
		}
		return renderFact(d, *f)
	}
}

func renderFact(d *firmware.Definition, f firmware.Fact) string {
	if len(f.Alts) > 0 {
		lines := make([]string, 0, len(f.Alts))
		for _, a := range f.Alts {
			lines = append(lines, renderOne(d, a))
		}
		return strings.Join(lines, "<br>")
	}
	return renderOne(d, f)
}

func renderOne(d *firmware.Definition, f firmware.Fact) string {
	var text string
	switch {
	case f.Hook != "":
		text = "hook: " + cellText(f.Hook)
	case f.Value != nil:
		text = cellText(strings.Join(f.Strings(), ", "))
	default:
		return ""
	}
	if f.Src != "" && d.Upstream.Repo != "" {
		text = fmt.Sprintf("[%s](https://%s/blob/%s/%s)", text, d.Upstream.Repo, d.Upstream.Ref, escapePath(f.Src))
	}
	return text + rangeSuffix(f.Since, f.Until)
}

func rangeSuffix(since, until string) string {
	var s string
	if since != "" {
		s += " (since " + cellText(since) + ")"
	}
	if until != "" {
		s += " (until " + cellText(until) + ")"
	}
	return s
}

func versionCell(d *firmware.Definition) string {
	var lines []string
	if s := renderFact(d, d.Version.File); s != "" {
		lines = append(lines, s)
	}
	if d.Version.Hook != "" {
		lines = append(lines, "hook: "+cellText(d.Version.Hook))
	}
	return strings.Join(lines, "<br>")
}

func savesHooksCell(d *firmware.Definition) string {
	var lines []string
	if d.Saves.NamingHook != "" {
		lines = append(lines, "naming: hook: "+cellText(d.Saves.NamingHook))
	}
	if d.Saves.ExtraFoldersHook != "" {
		lines = append(lines, "extra folders: hook: "+cellText(d.Saves.ExtraFoldersHook))
	}
	if d.Saves.LabelHook != "" {
		lines = append(lines, "label: hook: "+cellText(d.Saves.LabelHook))
	}
	return strings.Join(lines, "<br>")
}

func launcherCell(d *firmware.Definition) string {
	le := d.Gamelist.LauncherEntry
	if le == nil {
		return ""
	}
	return cellText(fmt.Sprintf("%s in %s", le.Gamelist, le.Path))
}

func rulesCell(d *firmware.Definition) string {
	lines := make([]string, 0, len(d.Devices.Rules))
	for _, r := range d.Devices.Rules {
		var s string
		switch {
		case r.Env != "" && r.Prefix != "":
			s = fmt.Sprintf("%s: env %s prefix %s", r.Device, r.Env, r.Prefix)
		case r.Env != "":
			s = fmt.Sprintf("%s: env %s = %s", r.Device, r.Env, r.Equals)
		default:
			s = fmt.Sprintf("%s: file %s contains %s", r.Device, r.File, r.Contains)
		}
		lines = append(lines, cellText(s))
	}
	return strings.Join(lines, "<br>")
}

func inputsCell(d *firmware.Definition) string {
	keys := make([]string, 0, len(d.Devices.Inputs))
	for k := range d.Devices.Inputs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	lines := make([]string, 0, len(keys))
	for _, k := range keys {
		in := d.Devices.Inputs[k]
		v := in.File
		if in.Hook != "" {
			v = "hook: " + in.Hook
		}
		lines = append(lines, cellText(k+": "+v))
	}
	return strings.Join(lines, "<br>")
}

func quirksCell(d *firmware.Definition) string {
	keys := make([]string, 0, len(d.Devices.Quirks))
	for k := range d.Devices.Quirks {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	lines := make([]string, 0, len(keys))
	for _, k := range keys {
		q := d.Devices.Quirks[k]
		var parts []string
		if q.Rotation != 0 {
			parts = append(parts, "rotation "+strconv.Itoa(q.Rotation))
		}
		if q.DisableKeyboardJoystick {
			parts = append(parts, "disable_keyboard_joystick")
		}
		lines = append(lines, cellText(k+": "+strings.Join(parts, ", ")))
	}
	return strings.Join(lines, "<br>")
}

func sourcesCell(d *firmware.Definition) string {
	keys := make([]string, 0, len(d.PlatformSources))
	for k := range d.PlatformSources {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	lines := make([]string, 0, len(keys))
	for _, k := range keys {
		path := d.PlatformSources[k]
		v := cellText(path)
		if d.Upstream.Repo != "" {
			v = fmt.Sprintf("[%s](https://%s/blob/%s/%s)", v, d.Upstream.Repo, d.Upstream.Ref, escapePath(path))
		}
		lines = append(lines, cellText(k)+": "+v)
	}
	return strings.Join(lines, "<br>")
}

func platformRows(defs []*firmware.Definition) [][]string {
	slugSet := map[string]bool{}
	for _, d := range defs {
		for s := range d.Platforms {
			slugSet[s] = true
		}
	}
	slugs := make([]string, 0, len(slugSet))
	for s := range slugSet {
		slugs = append(slugs, s)
	}
	sort.Strings(slugs)

	rows := make([][]string, 0, len(slugs)+1)
	sources := []string{"sources"}
	for _, d := range defs {
		sources = append(sources, sourcesCell(d))
	}
	rows = append(rows, sources)
	for _, s := range slugs {
		line := []string{cellText(s)}
		for _, d := range defs {
			p, ok := d.Platforms[s]
			if !ok {
				line = append(line, "")
				continue
			}
			lines := []string{"-"}
			if len(p.Roms) > 0 {
				lines = []string{cellText(strings.Join(p.Roms, ", "))}
			}
			if len(p.Roms) > 0 || len(p.Saves) > 0 {
				lines = append(lines, "saves: "+cellText(strings.Join(p.Saves, ", ")))
			}
			if p.System != "" {
				lines = append(lines, "system: "+cellText(p.System))
			}
			if len(p.Bios) > 0 {
				lines = append(lines, "bios: "+cellText(strings.Join(p.Bios, ", ")))
			}
			cell := strings.Join(lines, "<br>") + rangeSuffix(p.Since, p.Until)
			line = append(line, cell)
		}
		rows = append(rows, line)
	}
	return rows
}

func escapePath(p string) string {
	parts := strings.Split(p, "/")
	for i, s := range parts {
		parts[i] = url.PathEscape(s)
	}
	return strings.Join(parts, "/")
}
